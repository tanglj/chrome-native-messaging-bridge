# 注册 Chrome Native Messaging Host（Windows）。
# 用法: scripts\register-chrome.ps1 [-ExtensionId <扩展ID>] [-HostName <宿主名称>]
# 缺省扩展 ID 从 extension/manifest.json 的 key 字段派生（与 Chrome 的 ID 算法一致）。
# Chrome 在 Windows 上从注册表读取 manifest:
#   HKCU\Software\Google\Chrome\NativeMessagingHosts\<宿主名称>（64 位 Chrome）
#   HKCU\Software\WOW6432Node\Google\Chrome\NativeMessagingHosts\<宿主名称>（32 位 Chrome）
[CmdletBinding()]
param(
  [Parameter(Position = 0)]
  [string]$ExtensionId = "",
  [Parameter(Position = 1)]
  [string]$HostName = "com.local.native_bridge"
)

$ErrorActionPreference = "Stop"

$Root = Split-Path -Parent $PSScriptRoot
$ManifestSrc = Join-Path $Root "extension\manifest.json"
$HostDir = Join-Path $Root "host"
$HostScript = Join-Path $HostDir "native-host.mjs"
$Launcher = Join-Path $HostDir "$HostName.cmd"
$HostManifest = Join-Path $HostDir "$HostName.win.json"

if ($HostName -notmatch '^[a-z0-9_]+(\.[a-z0-9_]+)*$') {
  throw "非法宿主名称: $HostName"
}
if (-not (Test-Path $HostScript)) {
  throw "未找到宿主脚本: $HostScript"
}
if (-not (Test-Path $ManifestSrc)) {
  throw "未找到扩展 manifest: $ManifestSrc"
}

# 1. 确认 node 可用（启动器在运行时按常见安装位置和 PATH 解析 node）。
$Node = Get-Command node -ErrorAction SilentlyContinue
if (-not $Node) {
  throw "未找到 node，请先安装 Node.js 18+（https://nodejs.org/）。"
}
$NodePath = $Node.Source
$NodeVersion = (& $NodePath --version).Trim()
if ($NodeVersion -match '^v(\d+)\.' -and [int]$Matches[1] -lt 18) {
  throw "Node.js 版本过低（$NodeVersion），请安装 18+。"
}

# 2. 派生缺省扩展 ID：SHA256(SPKI DER) 前 128bit，0-9a-f 映射为 a-p（与 Chrome 算法一致）。
if (-not $ExtensionId) {
  # 显式按 UTF-8 读取，避免 Windows PowerShell 5.1 对无 BOM 文件使用 ANSI 解码。
  $ManifestText = [System.IO.File]::ReadAllText($ManifestSrc, [System.Text.Encoding]::UTF8)
  $Manifest = $ManifestText | ConvertFrom-Json
  $Key = $Manifest.key
  if (-not $Key) {
    throw 'manifest.json 中没有 key 字段，请显式传入扩展 ID。'
  }
  $Digest = [System.Security.Cryptography.SHA256]::Create().ComputeHash(
    [Convert]::FromBase64String($Key)
  )
  $Alphabet = 'abcdefghijklmnop'
  $IdChars = foreach ($Byte in $Digest[0..15]) {
    $Alphabet[$Byte -shr 4]
    $Alphabet[$Byte -band 0xF]
  }
  $ExtensionId = -join $IdChars
}
if ($ExtensionId -notmatch '^[a-p]{32}$') {
  throw "非法扩展 ID: $ExtensionId"
}

# 3. 生成宿主启动器（ASCII，避免 cmd.exe 代码页问题；项目目录按启动脚本自身位置解析）。
#    注册时解析到的 node 绝对路径为纯 ASCII 时优先写入，Chrome 继承的 PATH 不含该目录也能启动。
$BakedNodeLine = ""
if ($NodePath -notmatch '[^\x20-\x7E]' -and $NodePath -notmatch '%') {
  $BakedNodeLine = 'if exist "' + $NodePath + '" set "NODE=' + $NodePath + '"'
}
$LauncherContent = @"
@echo off
setlocal
rem Generated by scripts/register-chrome.ps1. Prefer the node path resolved at registration.
set "NODE="
$BakedNodeLine
if not defined NODE if exist "%ProgramFiles%\nodejs\node.exe" set "NODE=%ProgramFiles%\nodejs\node.exe"
if not defined NODE if exist "%ProgramFiles(x86)%\nodejs\node.exe" set "NODE=%ProgramFiles(x86)%\nodejs\node.exe"
if not defined NODE if exist "%LocalAppData%\Programs\nodejs\node.exe" set "NODE=%LocalAppData%\Programs\nodejs\node.exe"
if not defined NODE for /f "delims=" %%I in ('where node 2^>nul') do if not defined NODE set "NODE=%%I"
if not defined NODE exit /b 1
"%NODE%" "%~dp0native-host.mjs" %*
"@
Set-Content -Path $Launcher -Value $LauncherContent -Encoding ASCII

# 4. 生成宿主 manifest，path 指向 .cmd 启动器（Windows 下 Chrome 支持批处理包装）。
$ManifestObject = [ordered]@{
  name            = $HostName
  description     = "Chrome Native Messaging bridge host"
  path            = $Launcher
  type            = "stdio"
  allowed_origins = @("chrome-extension://$ExtensionId/")
}
$ManifestJson = $ManifestObject | ConvertTo-Json -Depth 5
[System.IO.File]::WriteAllText(
  $HostManifest,
  $ManifestJson + "`r`n",
  (New-Object System.Text.UTF8Encoding($false))
)

# 5. 写入注册表（HKCU 无需管理员权限），默认值指向宿主 manifest 绝对路径。
$RegistryPaths = @(
  "HKCU:\Software\Google\Chrome\NativeMessagingHosts\$HostName",
  "HKCU:\Software\WOW6432Node\Google\Chrome\NativeMessagingHosts\$HostName"
)
foreach ($RegistryPath in $RegistryPaths) {
  New-Item -Path $RegistryPath -Force | Out-Null
  Set-ItemProperty -Path $RegistryPath -Name "(Default)" -Value $HostManifest
}

Write-Host "已注册 Chrome 原生宿主:"
Write-Host "  宿主名称: $HostName"
Write-Host "  注册表:   $($RegistryPaths -join ' ; ')"
Write-Host "  manifest: $HostManifest"
Write-Host "  启动脚本: $Launcher"
Write-Host "  node:     $NodePath ($NodeVersion)"
Write-Host "  扩展 ID:  $ExtensionId"
